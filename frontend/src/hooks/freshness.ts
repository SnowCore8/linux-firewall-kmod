/**
 * 跨来源的「新鲜度戳」发生器。
 *
 * 做什么：提供一个进程内单调递增的计数器。每当**某个来源成功写入了一份数据**就取一个
 *         戳；戳大者即「写入更晚者」。
 *
 * 影响什么：`useSse` 的各域载荷与 `useAsync` 的取数结果都用它记录时间，再由
 *          [`pickLiveData`](./useLiveData.ts) 比较决定渲染哪一份。二者**必须共用一个
 *          发生器**——若各自维护独立计数器，比较就退化成「谁计的数更大」而不是「谁更新」：
 *          例如 REST 每 5 s 轮询一次、SSE 每 1 s 推一帧时，独立计数器下 REST 的计数值会
 *          在小节拍上反超 SSE，把更旧的 REST 快照判成更新的那一份。
 *
 * 边界：只在单个页面会话内单调（刷新页面即归零），因此**不跨页面/跨标签比较**。
 */

let stamp = 0

/** 取下一个新鲜度戳。返回值恒为正，故 0 可以安全地表示「还没写入过」。 */
export function nextFreshnessStamp(): number {
  stamp += 1
  return stamp
}
